String languageCode(SupportedLanguage language) =>
    language == SupportedLanguage.en ? 'en' : 'mm';

SupportedLanguage? languageFromCode(String? code) {
  switch (code) {
    case 'en':
      return SupportedLanguage.en;
    case 'mm':
      return SupportedLanguage.mm;
    default:
      return null;
  }
}

/// Dotted-path lookup, e.g. t('auth.login.title'), mirroring the loose
/// `Translations = Record<string, any>` access pattern used throughout the RN app.
extension TranslationsLookup on Map<String, dynamic> {
  String t(String path) {
    dynamic node = this;
    for (final segment in path.split('.')) {
      if (node is Map<String, dynamic> && node.containsKey(segment)) {
        node = node[segment];
      } else {
        return path;
      }
    }
    return node is String ? node : path;
  }
}

